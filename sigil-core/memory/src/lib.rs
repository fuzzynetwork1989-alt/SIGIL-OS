/// Memory source tracking
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum MemorySource {
    Conversation { conversation_id: Uuid },
    ManualEntry { user_id: Uuid },
    ObservedBehavior { behavior: String },
    External { source_name: String, url: Option<String> },
    Inference { model: String },
}

/// Verification status for memories
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub enum VerificationStatus {
    Unverified,
    Confirmed,
    Contradicted,
    Outdated,
}

/// Memory error types
#[derive(Debug, thiserror::Error)]
pub enum MemoryError {
    #[error("Memory not found: {0}")]
    NotFound(Uuid),
    
    #[error("Storage error: {0}")]
    Storage(String),
    
    #[error("Vector database error: {0}")]
    VectorDatabase(String),
    
    #[error("Confidence calculation error: {0}")]
    Confidence(String),
    
    #[error("Invalid memory operation: {0}")]
    InvalidOperation(String),
    
    #[error("Permission denied: {0}")]
    PermissionDenied(String),
}

/// Memory system configuration
#[derive(Debug, Clone)]
pub struct MemoryConfig {
    pub qdrant_url: String,
    pub embedding_dimension: usize,
    pub confidence_threshold: f32,
    pub retention_days: u32,
}

impl Default for MemoryConfig {
    fn default() -> Self {
        Self {
            qdrant_url: "http://localhost:6333".to_string(),
            embedding_dimension: 1536, // OpenAI embedding dimension
            confidence_threshold: 0.5,
            retention_days: 365,
        }
    }
}

/// Main memory system
pub struct MemorySystem {
    config: MemoryConfig,
    vector_db: VectorDatabase,
    confidence_calculator: ConfidenceCalculator,
}

impl MemorySystem {
    /// Create a new memory system
    pub async fn new(config: MemoryConfig) -> Result<Self> {
        let vector_db = VectorDatabase::new(&config.qdrant_url).await?;
        let confidence_calculator = ConfidenceCalculator::new();
        
        Ok(Self {
            config,
            vector_db,
            confidence_calculator,
        })
    }
    
    /// Store a memory entry
    pub async fn store_memory(
        &self,
        content: String,
        memory_type: MemoryType,
        source: MemorySource,
    ) -> Result<Uuid> {
        let id = Uuid::new_v4();
        
        // Generate embedding (placeholder - would use OpenAI API)
        let embedding = self.generate_embedding(&content).await?;
        
        // Calculate confidence
        let confidence = self.confidence_calculator.calculate(&source);
        
        // Create memory entry
        let memory = MemoryEntry {
            id,
            memory_type,
            content,
            embedding: Some(embedding),
            timestamp: Utc::now(),
            source,
            confidence,
            verification_status: VerificationStatus::Unverified,
            sigil: None, // Would be generated by sigil system
            related_memories: Vec::new(),
            tags: Vec::new(),
        };
        
        // Store in vector database
        self.vector_db.store_memory(&memory).await?;
        
        Ok(id)
    }
    
    /// Retrieve a memory by ID
    pub async fn retrieve_memory(&self, id: Uuid) -> Result<MemoryEntry> {
        self.vector_db.retrieve_memory(id).await
    }
    
    /// Search memories by similarity
    pub async fn search_memory(
        &self,
        query: String,
        memory_type: MemoryType,
        limit: usize,
    ) -> Result<Vec<MemoryEntry>> {
        let query_embedding = self.generate_embedding(&query).await?;
        self.vector_db
            .search_by_embedding(&query_embedding, memory_type, limit)
            .await
    }
    
    /// Update a memory
    pub async fn update_memory(&self, id: Uuid, new_content: String) -> Result<()> {
        let old_memory = self.retrieve_memory(id).await?;
        let new_embedding = self.generate_embedding(&new_content).await?;
        
        let updated_memory = MemoryEntry {
            content: new_content,
            embedding: Some(new_embedding),
            timestamp: Utc::now(),
            ..old_memory
        };
        
        self.vector_db.update_memory(&updated_memory).await
    }
    
    /// Delete a memory
    pub async fn delete_memory(&self, id: Uuid) -> Result<()> {
        self.vector_db.delete_memory(id).await
    }
    
    /// Generate embedding (placeholder implementation)
    async fn generate_embedding(&self, content: &str) -> Result<Vec<f32>> {
        // Placeholder: In production, this would call OpenAI embedding API
        // For now, return a zero vector of the correct dimension
        Ok(vec![0.0; self.config.embedding_dimension])
    }
}

